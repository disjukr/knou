# 95% 신뢰구간
# t 분포 이용
c(75 + qt(0.025, 99) * 5 / sqrt(100), 75 + qt(0.975, 99) * 5 / sqrt(100))
# 정규분포 이용
c(75 + qnorm(0.025) * 5 / sqrt(100), 75 + qnorm(0.975) * 5 / sqrt(100))

# 99% 신뢰구간
# t 분포 이용, 표본 수 100
c(75 + qt(0.005, 99) * 5 / sqrt(100), 75 + qt(0.995, 99) * 5 / sqrt(100))

